        // ── Data reading ─────────────────────────────────────────────────────────

        private RpcContainerData ReadContainerData(SourceProductionContext sourceContext, SemanticModel typeSem, AttributeSyntax attr)
        {
            var args = attr.ArgumentList?.Arguments;
            if (args == null || args.Value.Count < 2)
            {
                sourceContext.ShowRpcDiagnostics("NSLRPC001", "NSLRPCImplementAttribute requires Interface and NetworkDataType", DiagnosticSeverity.Error, attr.GetLocation());
                return null;
            }

            var interfaceType = args.Value[0].GetAttributeTypeParameterValueSymbol(typeSem);
            var networkDataType = args.Value[1].GetAttributeTypeParameterValueSymbol(typeSem);

            if (interfaceType == null || networkDataType == null)
            {
                sourceContext.ShowRpcDiagnostics("NSLRPC002", "Cannot resolve Interface or NetworkDataType type argument", DiagnosticSeverity.Error, attr.GetLocation());
                return null;
            }

            var direction = NSLRPCDirection.Both;

            var namedArgs = args.Value.Where(a => a.NameEquals != null).ToDictionary(a => a.NameEquals.Name.ToString(), a => a);

            if (namedArgs.TryGetValue(nameof(NSLRPCImplementAttribute.Direction), out var dirArg))
                direction = dirArg.GetAttributeParameterValue<NSLRPCDirection>(typeSem);

            bool interfaceHasExceptionHandler = interfaceType.GetAttributes()
                .Any(a => a.AttributeClass.Name.Equals(NSLRPCExceptionHandlerAttributeFullName));

            var container = new RpcContainerData
            {
                InterfaceType = interfaceType,
                NetworkDataType = networkDataType,
                Direction = direction
            };

            LoadMethods(sourceContext, typeSem, container, interfaceHasExceptionHandler);

            return container;
        }

        private void LoadMethods(SourceProductionContext sourceContext, SemanticModel typeSem, RpcContainerData container, bool interfaceHasExceptionHandler)
        {
            foreach (var member in container.InterfaceType.GetAllMembers())
            {
                if (!(member is IMethodSymbol ms))
                    continue;

                var methodAttrs = ms.GetAttributes();

                var rpcAttr = methodAttrs.FirstOrDefault(a => a.AttributeClass.Name.Equals(NSLRPCMethodAttributeFullName));
                if (rpcAttr == null)
                    continue;

                var pid = (ushort)rpcAttr.ConstructorArguments[0].Value;

                string binaryModel = null;
                var binaryModelArg = rpcAttr.NamedArguments.FirstOrDefault(n => n.Key == nameof(NSLRPCMethodAttribute.BinaryModel));
                if (!binaryModelArg.Equals(default) && binaryModelArg.Value.Value is string bm && !string.IsNullOrEmpty(bm))
                    binaryModel = bm;

                bool isFireAndForget = methodAttrs.Any(a => a.AttributeClass.Name.Equals(NSLRPCFireAndForgetAttributeFullName));

                bool hasExceptionHandler = !isFireAndForget && (
                    interfaceHasExceptionHandler ||
                    methodAttrs.Any(a => a.AttributeClass.Name.Equals(NSLRPCExceptionHandlerAttributeFullName)));

                // Determine result: Task<T> → T, plain Task → null
                RpcResultData result = null;
                if (!isFireAndForget)
                {
                    var returnType = ms.ReturnType as INamedTypeSymbol;
                    if (returnType != null && returnType.TypeArguments.Length == 1)
                    {
                        result = new RpcResultData
                        {
                            Type = returnType.TypeArguments[0],
                            BinaryModel = binaryModel
                        };
                    }
                }

                var parameters = ms.Parameters.Select(p => new RpcParamData
                {
                    Type = p.Type,
                    Name = p.Name,
                    BinaryModel = binaryModel
                }).ToArray();

                container.Methods.Add(new RpcMethodData
                {
                    Name = ms.Name,
                    Pid = pid,
                    Parameters = parameters,
                    Result = result,
                    IsFireAndForget = isFireAndForget,
                    HasExceptionHandler = hasExceptionHandler,
                    MethodSymbol = ms
                });
            }
        }

        // ── Constants ────────────────────────────────────────────────────────────

        internal static readonly string NSLRPCImplementAttributeFullName        = typeof(NSLRPCImplementAttribute).Name;
        internal static readonly string NSLRPCMethodAttributeFullName           = typeof(NSLRPCMethodAttribute).Name;
        internal static readonly string NSLRPCFireAndForgetAttributeFullName    = typeof(NSLRPCFireAndForgetAttribute).Name;
        internal static readonly string NSLRPCExceptionHandlerAttributeFullName = typeof(NSLRPCExceptionHandlerAttribute).Name;
        internal static readonly string NSLBIOTypeAttributeFullName             = typeof(NSLBIOTypeAttribute).Name;
    }
