    [Generator]
    internal class NSLRPCGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var pip = context.SyntaxProvider.CreateSyntaxProvider(
                NSLRPCSyntaxReceiver.OnVisitSyntaxNode,
                (syntax, _) => syntax);

            context.RegisterSourceOutput(pip, ProcessRpcType);
        }

        private void ProcessRpcType(SourceProductionContext context, GeneratorSyntaxContext item)
        {
            var @class = (ClassDeclarationSyntax)item.Node;
            try
            {
                ProcessRpcClass(context, item, @class);
            }
            catch (Exception ex)
            {
                context.ShowRpcDiagnostics("NSLRPC999", $"Error on build {ex}", DiagnosticSeverity.Error, @class.GetLocation());
            }
        }

        private void ProcessRpcClass(SourceProductionContext sourceContext, GeneratorSyntaxContext context, ClassDeclarationSyntax typeClass)
        {
            if (!typeClass.HasPartialModifier())
            {
                sourceContext.ShowRpcDiagnostics("NSLRPC000", "Type must have a partial modifier", DiagnosticSeverity.Error, typeClass.GetLocation());
                return;
            }

            var typeSem = context.SemanticModel;
            var codeBuilder = new CodeBuilder();

            codeBuilder.AppendComment(() =>
            {
                codeBuilder.AppendLine("Auto Generated by NSL RPC Generator. Please don't change this file");
                codeBuilder.AppendLine("Project must have reference to \"NSL.SocketCore\" for normal working");
            });

            List<string> usings = new List<string>
            {
                "NSL.SocketCore",
                "NSL.SocketCore.Utils.Buffer",
                "NSL.SocketCore.Utils.Request",
                "NSL.Generators.RpcGenerator.Shared",
                "System",
                "System.Linq",
                "System.Threading",
                "System.Threading.Tasks"
            };

            codeBuilder.CreatePartialClass((CSharpCompilation)typeSem.Compilation, typeClass, classBuilder =>
            {
                var implAttrs = typeClass.AttributeLists
                    .SelectMany(x => x.Attributes)
                    .Where(x => x.GetAttributeFullName().Equals(NSLRPCImplementAttributeFullName))
                    .ToArray();

                var containers = new List<RpcContainerData>();
                bool hasClientSide = false;

                foreach (var attr in implAttrs)
                {
                    var container = ReadContainerData(sourceContext, typeSem, attr);
                    if (container == null) continue;

                    containers.Add(container);

                    if (container.Direction.HasFlag(NSLRPCDirection.Client))
                        hasClientSide = true;
                }

                if (hasClientSide)
                {
                    classBuilder.AppendLine("protected partial NSL.Generators.RpcGenerator.Shared.IRPCNetworkChannel GetRpcChannel();");
                    classBuilder.AppendLine();
                }

                foreach (var container in containers)
                {
                    // Add usings from interface's file
                    var syntaxRef = container.InterfaceType.DeclaringSyntaxReferences.FirstOrDefault();
                    if (syntaxRef != null)
                    {
                        var root = syntaxRef.SyntaxTree.GetRoot();
                        root.DescendantNodes()
                            .OfType<UsingDirectiveSyntax>()
                            .Select(u => string.Join(" ", u.ToString().Split(' ').Skip(1)).TrimEnd(';').Trim())
                            .ToList()
                            .ForEach(u => usings.Add(u));
                    }

                    if (container.Direction.HasFlag(NSLRPCDirection.Client))
                        BuildClientCode(sourceContext, classBuilder, container);

                    if (container.Direction.HasFlag(NSLRPCDirection.Server))
                        BuildServerCode(sourceContext, classBuilder, container);
                }

            }, usings);

            sourceContext.AddSource($"{typeClass.GetTypeClassName()}.rpc.cs", codeBuilder.ToString());
        }

        // ── Client side ─────────────────────────────────────────────────────────

        private void BuildClientCode(SourceProductionContext sourceContext, CodeBuilder classBuilder, RpcContainerData container)
        {
            foreach (var method in container.Methods)
            {
                BuildClientMethod(sourceContext, classBuilder, container, method);
                classBuilder.AppendLine();
            }
        }

        private void BuildClientMethod(SourceProductionContext sourceContext, CodeBuilder classBuilder, RpcContainerData container, RpcMethodData method)
        {
            classBuilder.AppendSummaryLine($"RPC client stub for <see cref=\"{container.InterfaceType.GetTypeFullName()}.{method.Name}\"/>. Pid = {method.Pid}");

            if (method.IsFireAndForget)
            {
                // FAF: void return, OutputPacketBuffer, GetRpcChannel().Send()
                var fafParams = method.Parameters.Select(p => $"{p.Type.GetTypeFullName()} {p.Name}").ToList();
                classBuilder.AppendLine($"public void {method.Name}({string.Join(", ", fafParams)})");
                classBuilder.AppendBodyTabContent(() =>
                {
                    classBuilder.AppendLine($"var __outputBuf = {nameof(OutputPacketBuffer)}.Create({method.Pid});");
                    foreach (var p in method.Parameters)
                        classBuilder.AppendLine($"{BuildParamWriteSegment(sourceContext, p, p.Name, "__outputBuf")};");
                    classBuilder.AppendLine();
                    classBuilder.AppendLine("GetRpcChannel().Send(__outputBuf);");
                });
                return;
            }

            // Default: request-response (Task or Task<T>)
            bool hasResult = method.Result != null;
            var reqParams = method.Parameters.Select(p => $"{p.Type.GetTypeFullName()} {p.Name}").ToList();
            reqParams.Add("System.Threading.CancellationToken __cancellationToken = default");

            string returnType = hasResult
                ? $"async Task<{method.Result.Type.GetTypeFullName()}>"
                : "async Task";

            classBuilder.AppendLine($"public {returnType} {method.Name}({string.Join(", ", reqParams)})");
            classBuilder.AppendBodyTabContent(() =>
            {
                classBuilder.AppendLine($"var __outputBuf = RequestPacketBuffer.Create({method.Pid});");
                foreach (var p in method.Parameters)
                    classBuilder.AppendLine($"{BuildParamWriteSegment(sourceContext, p, p.Name, "__outputBuf")};");

                classBuilder.AppendLine();
                classBuilder.AppendLine("using var __response = await GetRpcChannel().RequestAsync(__outputBuf, __cancellationToken);");

                if (method.HasExceptionHandler)
                {
                    classBuilder.AppendLine("if (!__response.ReadBool())");
                    classBuilder.AppendBodyTabContent(() =>
                        classBuilder.AppendLine("throw new NSLRPCRemoteException(__response.ReadString(), __response.ReadString());"));
                }

                if (hasResult)
                {
                    classBuilder.AppendLine();
                    classBuilder.AppendLine($"return {BuildResultReadSegment(sourceContext, method.Result, method.Result.Type.GetTypeFullName(), "__response")};");
                }
            });
        }

        // ── Server side ─────────────────────────────────────────────────────────

        private void BuildServerCode(SourceProductionContext sourceContext, CodeBuilder classBuilder, RpcContainerData container)
        {
            var configureBuilder = new CodeBuilder();

            configureBuilder.AppendLine($"public void NSLConfigureRpcHandles_{container.InterfaceType.Name}({nameof(CoreOptions)}<{container.NetworkDataType.GetTypeFullName()}> options)");
            configureBuilder.AppendBodyTabContent(() =>
            {
                foreach (var method in container.Methods)
                {
                    BuildServerHandler(sourceContext, classBuilder, container, method);
                    classBuilder.AppendLine();

                    configureBuilder.AppendLine($"options.{nameof(CoreOptions<BaseNetworkConnection>.AddAsyncHandle)}({method.Pid}, NSLRpcHandle_{method.Name});");
                }
            });

            classBuilder.AppendLine(configureBuilder.ToString());
        }

        private void BuildServerHandler(SourceProductionContext sourceContext, CodeBuilder classBuilder, RpcContainerData container, RpcMethodData method)
        {
            string clientType = container.NetworkDataType.GetTypeFullName();
            bool hasResult = method.Result != null;

            classBuilder.AppendSummaryLine($"RPC server handler for <see cref=\"{container.InterfaceType.GetTypeFullName()}.{method.Name}\"/>. Pid = {method.Pid}");
            classBuilder.AppendLine($"private async System.Threading.Tasks.Task NSLRpcHandle_{method.Name}({clientType} client, {nameof(InputPacketBuffer)} data)");
            classBuilder.AppendBodyTabContent(() =>
            {
                // FAF: no response at all
                if (method.IsFireAndForget)
                {
                    foreach (var p in method.Parameters)
                        classBuilder.AppendLine($"{p.Type.GetTypeFullName()} {p.Name} = {BuildParamReadSegment(sourceContext, p, p.Type.GetTypeFullName(), "data")};");
                    classBuilder.AppendLine();
                    classBuilder.AppendLine($"await {method.Name}({string.Join(", ", method.Parameters.Select(p => p.Name))});");
                    return;
                }

                // Request-response
                classBuilder.AppendLine("var __response = data.CreateResponse();");
                classBuilder.AppendLine();

                foreach (var p in method.Parameters)
                    classBuilder.AppendLine($"{p.Type.GetTypeFullName()} {p.Name} = {BuildParamReadSegment(sourceContext, p, p.Type.GetTypeFullName(), "data")};");

                var callArgs = string.Join(", ", method.Parameters.Select(p => p.Name));
                classBuilder.AppendLine();

                if (method.HasExceptionHandler)
                {
                    classBuilder.AppendLine("try");
                    classBuilder.AppendBodyTabContent(() => BuildServerInvoke(sourceContext, classBuilder, method, callArgs, hasResult, "__response", writeSuccessFlag: true));
                    classBuilder.AppendLine("catch (System.Exception __ex)");
                    classBuilder.AppendBodyTabContent(() =>
                    {
                        classBuilder.AppendLine("__response.WriteBool(false);");
                        classBuilder.AppendLine("__response.WriteString(__ex.GetType().FullName);");
                        classBuilder.AppendLine("__response.WriteString(__ex.Message);");
                    });
                }
                else
                {
                    BuildServerInvoke(sourceContext, classBuilder, method, callArgs, hasResult, "__response", writeSuccessFlag: false);
                }

                classBuilder.AppendLine();
                classBuilder.AppendLine("client.Send(__response);");
            });
        }

        private void BuildServerInvoke(SourceProductionContext sourceContext, CodeBuilder classBuilder, RpcMethodData method, string callArgs, bool hasResult, string responseBuf, bool writeSuccessFlag)
        {
            if (hasResult)
            {
                classBuilder.AppendLine($"var ___result = await {method.Name}({callArgs});");
                if (writeSuccessFlag)
                    classBuilder.AppendLine($"{responseBuf}.WriteBool(true);");
                classBuilder.AppendLine($"{BuildResultWriteSegment(sourceContext, method.Result, "___result", responseBuf)};");
            }
            else
            {
                classBuilder.AppendLine($"await {method.Name}({callArgs});");
                if (writeSuccessFlag)
                    classBuilder.AppendLine($"{responseBuf}.WriteBool(true);");
            }
        }

        // ── Binary serialization helpers ─────────────────────────────────────────

        private string BuildParamReadSegment(SourceProductionContext sourceContext, RpcParamData param, string typeName, string ioPath)
        {
            var typeAttributes = param.Type.GetAttributes()
                .Where(x => x.AttributeClass.Name.Equals(NSLBIOTypeAttributeFullName)).ToArray();

            var typeModels = typeAttributes
                .SelectMany(x => x.ConstructorArguments.SelectMany(n => n.Values.Select(d => (string)d.Value)))
                .DefaultIfEmpty("<!!_NSLBIOFULL_!!>")
                .GroupBy(x => x).Select(x => x.Key)
                .ToArray();

            var model = param.BinaryModel ?? "<!!_NSLBIOFULL_!!>";

            if (typeAttributes.Length > 0 && typeModels.Contains(model))
            {
                return param.BinaryModel == null
                    ? $"{typeName}.ReadFullFrom({ioPath})"
                    : $"{typeName}.Read{param.BinaryModel}From({ioPath})";
            }

            return BinaryReadMethodsGenerator.GetValueReadSegment(param.Type, new BinaryGeneratorContext
            {
                Context = sourceContext,
                IOPath = ioPath,
                For = model
            }, ioPath);
        }

